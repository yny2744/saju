export function numerologyResult(solarDate: string): FunResult {
  const n = lifePathNumber(solarDate);
  const t = TEXT[n];
  const steps = solarDate.replace(/-/g, "").split("").join("+");
  return {
    key: String(n),
    badge: String(n),
    short: `인생 수 ${n}`,
    title: `인생 수 ${n} · ${t.name}`,
    subtitle: `${steps} → 인생 수 ${n}${n > 9 ? " (마스터 넘버)" : ""}`,
    body: t.body,
    tags: t.tags,
    element: lifePathElement(n),
    elementNote: `숫자 ${n > 9 ? `${n}(${n === 11 ? 2 : n === 22 ? 4 : 6})` : n}은 동양의 하도(河圖) 수로 ${lifePathElement(n)}의 기운이에요.`,
  };
}
