export function monthStone(solarDate: string): MonthStone {
  return MONTH[Number(solarDate.split("-")[1])];
}

export function birthstoneResult(solarDate: string): FunResult {
  const m = Number(solarDate.split("-")[1]);
  const s = MONTH[m];
  return {
    key: String(m),
    badge: s.name.slice(0, 1),
    short: s.name,
    title: `${m}월의 탄생석 · ${s.name}`,
    subtitle: `보석말: ${s.meaning}${s.also ? ` · 함께 쓰는 돌: ${s.also}` : ""}`,
    body: s.body,
    tags: s.meaning.split(" · "),
    element: s.element,
    elementNote: `${s.name}의 ${s.color}을 동양의 오행 색에 견주면 ${s.element}의 기운이에요.`,
  };
}
